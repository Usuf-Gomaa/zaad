import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
const file = 'ZAAD_RELIGIOUS_CONTENT_V2_1_SOURCE_CHECK_ADDENDUM.md';
const base = 'ZAAD_RELIGIOUS_CONTENT_V2_REVIEW_DRAFT.md';
const hash = value => createHash('sha256').update(value).digest('hex');
const sourceDocuments = [base, file].map(file => ({ file, sha256: hash(readFileSync(file)) }));
const fingerprint = hash(JSON.stringify(sourceDocuments));
writeFileSync('src/content/review-v2/source-identity.ts', `// Generated by npm run sources:identity. Both documents bind reviewer feedback.\nexport const reviewEdition = '2.1.0-draft';\nexport const reviewPackFile = ${JSON.stringify(base)};\nexport const sourceDocuments = ${JSON.stringify(sourceDocuments, null, 2)};\nexport const reviewPackSha256 = ${JSON.stringify(fingerprint)};\n`);
